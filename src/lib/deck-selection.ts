import { DEFAULT_DECK_ID } from "@/data/decks";

/**
 * "선택한 기본 덱"을 다루는 두 규칙의 순수 코어.
 *
 * 이 값은 리딩·일기와 달리 **타임스탬프 없는 단일 스칼라**다. 그래서 동기화
 * 계층이 기대는 LWW(더 최신이 이긴다)를 쓸 수단이 아예 없다. 규칙을 여기로
 * 떼어 둔 이유가 그것이다 — 물러설 곳이 없는 판단일수록 window도 서버도 모르는
 * 자리에서 시험할 수 있어야 한다.
 */

/**
 * 로그인 최초 병합에서 이 기기가 쓸 덱을 고른다.
 *
 * 원칙은 `first-merge.ts`가 세운 것을 그대로 가져온다 — "이 기기에 우연히 남아
 * 있던 게스트 잔재보다 계정에 쌓인 것이 낫다"(일기의 `"remote"` 정책).
 * **그래서 최초 병합에서는 서버가 이긴다.**
 *
 * 다만 컬럼 기본값이 `'classic'`이라 서버 값만으로는 **"한 번도 고른 적 없음"과
 * "명시적으로 클래식을 골랐음"을 구분할 수 없다.** 서버의 `'classic'`까지 의견으로
 * 취급하면, 손댄 적 없는 프로필이 사용자가 방금 게스트로 고른 덱을 조용히
 * 되돌린다. 그래서 `'classic'`은 "의견 없음"으로 읽고 로컬을 남긴다.
 *
 * 이 선택의 대가도 적어 둔다: 다른 기기에서 프리미엄 → 클래식으로 되돌린 사람이
 * 이 기기에서 처음 로그인하면 이 기기의 옛 선택이 되살아난다. 그러나 그것은 이
 * 기기의 **최초 병합 때 한 번**뿐이고 한 번 눌러 고칠 수 있는 선호값인 반면,
 * 반대 방향의 실수(방금 고른 덱이 이유 없이 사라짐)는 사용자가 원인을 알 수 없다.
 * 되돌릴 수 있는 쪽으로 틀리기를 택했다.
 */
export function resolveDeckOnLogin(local: string, remote: string): string {
  return remote !== DEFAULT_DECK_ID ? remote : local;
}
